export function getLanguageDirection(lang: Language): "rtl" | "ltr" {
  return lang === "ar" ? "rtl" : "ltr";
}

/**
 * Normalizes Arabic and English text for accurate, forgiving search matching.
 * Handles Alef variations (أ, إ, آ, ٱ -> ا), Ta Marbuta/Ha (ة -> ه), Ya/Alef Maksura (ى -> ي),
 * Hamza forms (ؤ, ئ -> و, ي), Tashkeel/Diacritics removal, Tatweel removal,
 * Arabic-Indic digits conversion (٠-٩ -> 0-9), and zero-width/invisible character removal.
 */
export function normalizeArabicText(input: string | undefined | null): string {
  if (!input) return "";
  return input
    .toString()
    .toLowerCase()
    // Remove diacritics / Tashkeel / Harakat
    .replace(/[\u064B-\u065F\u0670\u06D6-\u06ED]/g, "")
    // Remove tatweel (ـ)
    .replace(/\u0640/g, "")
    // Normalize Alef variations (أ, إ, آ, ٱ -> ا)
    .replace(/[أإآٱ]/g, "ا")
    // Normalize Ta Marbuta (ة -> ه)
    .replace(/ة/g, "ه")
    // Normalize Ya and Alef Maksura (ى -> ي)
    .replace(/ى/g, "ي")
    // Normalize Hamza forms (ؤ, ئ -> و, ي)
    .replace(/ؤ/g, "و")
    .replace(/ئ/g, "ي")
    // Convert Arabic-Indic numbers (٠-٩ -> 0-9)
    .replace(/[٠-٩]/g, (d) => (d.charCodeAt(0) - 1632).toString())
    // Convert Eastern Arabic-Indic numbers (۰-۹ -> 0-9)
    .replace(/[۰-۹]/g, (d) => (d.charCodeAt(0) - 1776).toString())
    // Strip zero-width & non-printable whitespace characters
    .replace(/[\u200B-\u200F\u202A-\u202E\uFEFF\u00A0]/g, " ")
    .trim();
}

/**
 * Checks if target strings contain all words of the search query in normalized format.
 */
export function matchesSearchQuery(
  searchQuery: string,
  ...targetFields: (string | undefined | null)[]
): boolean {
  const normQuery = normalizeArabicText(searchQuery);
  if (!normQuery) return true;

  const combinedTargets = targetFields
    .map((f) => normalizeArabicText(f))
    .join(" ");

  const words = normQuery.split(/\s+/).filter(Boolean);
  return words.every((word) => combinedTargets.includes(word));
}

